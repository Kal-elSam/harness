import { existsSync, readFileSync, statSync } from 'node:fs';
import { mkdir, open, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { backupFileBeforeChange } from '../backups.js';
import { writeAtomicText } from '../runtime/write-atomic-json.js';

export const openCodePacingMarker = 'Kairo quota pacing (managed)';
// OpenCode provides this package to its plugins; Kairo never imports it, so it is kept out of literal import syntax.
const OPENCODE_PLUGIN_PACKAGE = '@opencode/plugin';

export function renderOpenCodePacingPlugin(packageRoot, nodePath = process.execPath) {
  const module = pathToFileURL(join(packageRoot, 'src/global/hosts/opencode-pacing-plugin.js')).href;
  return `// ${openCodePacingMarker}. Generated by Kairo; \`kairo sync\` regenerates it. Requires OpenCode v2 plugins.
import { Plugin } from ${JSON.stringify(OPENCODE_PLUGIN_PACKAGE)};
import { createKairoPacingSetup } from ${JSON.stringify(module)};

export default Plugin.define({
  id: "kairo.pacing",
  setup: createKairoPacingSetup({ nodePath: ${JSON.stringify(nodePath)} }),
});
`;
}

export function planOpenCodePacing(context, remove = false) {
  const path = join(context.homeDir, '.config/opencode/plugins/kairo-pacing.js');
  const exists = existsSync(path);
  const current = exists ? readFileSync(path, 'utf8') : '';
  // A file without our marker belongs to the user: report it, never touch it.
  if (exists && !current.includes(openCodePacingMarker)) return { path, current, next: current, changed: false, foreign: true, remove };
  const packageRoot = context.packageRoot ?? fileURLToPath(new URL('../../../', import.meta.url));
  if (remove) return { path, current, next: '', changed: exists, foreign: false, remove };
  const next = renderOpenCodePacingPlugin(packageRoot);
  return { path, current, next, changed: next !== current, foreign: false, remove };
}

export async function applyOpenCodePacing(context, plan) {
  if (!plan.changed) return null;
  const exists = existsSync(plan.path);
  const current = exists ? readFileSync(plan.path, 'utf8') : '';
  if (current !== plan.current) throw new Error('OpenCode pacing plugin changed after planning; retry the install.');
  const backup = await backupFileBeforeChange({ backupsDir: context.paths.backupsDir, homeDir: context.homeDir,
    filePath: plan.path, timestamp: context.timestamp, dryRun: context.dryRun });
  if (!context.dryRun) {
    if (plan.remove) await rm(plan.path, { force: true });
    else {
      await mkdir(dirname(plan.path), { recursive: true });
      const mode = exists ? statSync(plan.path).mode & 0o777 : 0o600;
      await writeAtomicText(plan.path, plan.next, { open: (path, flags) => open(path, flags, mode) });
    }
  }
  return backup;
}
